import {mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {questions} from '../src/questions.js';
import {dailyQuestions,solve,normalize,PUZZLE_LENGTH} from '../src/logic.js';
const date=process.argv[2]||new Date().toISOString().slice(0,10);
if(!/^\d{4}-\d{2}-\d{2}$/.test(date)||new Date(date+'T00:00:00Z').toISOString().slice(0,10)!==date)throw Error('Invalid UTC date');
const chosen=dailyQuestions(questions,date);
const editor=solve(chosen);
if(!editor||editor.answers.length!==PUZZLE_LENGTH)throw Error('Puzzle is not solvable');
const signature=editor.answers.map(normalize).join('|');
const hash=createHash('sha256').update(signature).digest('hex');
const payload={date,questionIds:chosen.map(q=>q.id),editorChoiceHash:hash,editorChoiceLetters:editor.cost,version:2};
await mkdir('public/puzzles',{recursive:true});
await writeFile('public/puzzles/'+date+'.json',JSON.stringify(payload,null,2)+'\n');
console.log('Generated',date,'questions:',payload.questionIds.join(', '),'editor letters:',editor.cost);
